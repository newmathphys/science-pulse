DOMAIN_BRANCHES: Dict[str, List[Dict[str, Any]]] = {}
for _branch in BRANCHES:
    DOMAIN_BRANCHES.setdefault(str(_branch["domain"]), []).append(_branch)


def branch_step(index: int) -> int:
    """Ступень ветви: ``§ 11`` для первой ветви, ``§ 55`` для сорок пятой."""
    return START_STEP + max(0, int(index))


def _canon_parent(domain: str) -> List[str]:
    """Пререквизит первой ветви — узел канона последней ступени той же науки."""
    try:
        from .sources.foundation import CANON, step_of

        last_step = max((step_of(item["id"]) for item in CANON), default=1)
        best = [
            item for item in CANON
            if step_of(item["id"]) == last_step and item["domain"] == domain
        ]
        if not best:
            best = [item for item in CANON if step_of(item["id"]) == last_step]
        return [str(item["id"]) for item in best[:1]]
    except Exception:
        return []


def syllabus_topics() -> List[Dict[str, Any]]:
    """Все темы силлабуса с сквозными §-номерами, пререквизитами и tier."""
    topics: List[Dict[str, Any]] = []
    previous_last = ""
    for branch_index, branch in enumerate(BRANCHES):
        step = branch_step(branch_index)
        domain = str(branch["domain"])
        for topic_index, topic in enumerate(branch["topics"], start=1):
            if branch_index == 0 and topic_index == 1:
                parent = _canon_parent(domain)
            else:
                parent = [previous_last]
            section = f"{step}.{topic_index}"
            topics.append({
                "id": f"{branch['id']}-{topic_index}",
                "section_num": section,
                "step": step,
                "complexity_tier": step,
                "branch_id": branch["id"],
                "branch_title": branch["title"],
                "domain": domain,
                "title": f"{topic['title']}",
                "hook": topic["hook"],
                "formula_latex": topic["formula_latex"],
                "scientist": topic["scientist"],
                "era": f"Ступень {step} · университетский курс",
                "prereq_ids": [item for item in parent if item],
                "source_url": "",
                "source_name": "Университетский силлабус",
            })
            previous_last = section
    return topics


def syllabus_size() -> int:
    """Число тем в матрице университетского курса."""
    return sum(len(branch["topics"]) for branch in BRANCHES)


def next_syllabus_topics(count: int = 3, cycle: int = 0) -> List[Dict[str, Any]]:
    """Следующая порция тем для очереди публикации (детерминированно)."""
    topics = syllabus_topics()
    if not topics:
        return []
    start = max(0, int(cycle)) % len(topics)
    window = [topics[(start + offset) % len(topics)] for offset in range(max(1, int(count)))]
    return window


def find_topic(section: str) -> Optional[Dict[str, Any]]:
    """Тема по её §-номеру (``"11.2"``)."""
    for topic in syllabus_topics():
        if topic["section_num"] == str(section):
            return topic
    return None


def branches_for(domain: str) -> List[Dict[str, Any]]:
    """Ветви одной дисциплины в порядке возрастания сложности."""
    return list(DOMAIN_BRANCHES.get(domain, []))


def syllabus_summary() -> Dict[str, Any]:
    """Сводка матрицы курса: ветви, темы и диапазон ступеней."""
    topics = syllabus_topics()
    return {
        "branches": len(BRANCHES),
        "topics": len(topics),
        "first_section": topics[0]["section_num"] if topics else "",
        "last_section": topics[-1]["section_num"] if topics else "",
        "by_domain": {
            domain: len(items) for domain, items in sorted(DOMAIN_BRANCHES.items())
        },
    }
