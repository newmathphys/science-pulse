class HistoryCanonSource(Source):
    name = "history_canon"
    domains = ("math", "physics", "cs")
    tier = "history"

    def fetch(self, limit: int = 2, cycle: int = 0) -> List[Post]:
        posts: List[Post] = []
        for offset in range(max(1, limit)):
            index = cycle + offset
            if index >= len(CANON):
                break
            posts.append(self._build(CANON[index], index))
        return posts

    def _build(self, item: Dict[str, Any], index: int) -> Post:
        post = Post(
            id=make_id(self.name, item["id"]),
            domain=item["domain"],
            title=item["title"],
            hook=item["hook"],
            body=item["body"],
            formula_latex=item["formula_latex"],
            formula_plain=item["formula_plain"],
            code=item.get("code", ""),
            source_name=f"Хроника Науки · {item['scientist']}",
            source_url=item.get("source_url", ""),
            tier=self.tier,
            meta={"era": item["era"], "scientist": item["scientist"], "canon_index": index},
        )
        # «Тройная связь времени»: учёный+эпоха → формула+константы → применение сегодня.
        merged = dict(EXTRA_META.get(item["id"], {}))
        for key in META_KEYS:
            if key in item:
                merged[key] = item[key]
        merged["canon_id"] = item["id"]
        post.meta.update(merged)
        post.quality = post.quality_score()
        return post
